#!/usr/bin/env python3
"""Generates src/recursos/big5_tabla.inc (CP950 -> UTF-16 table) from Python's cp950 codec.
Index: (lead - 0x81) * 191 + (trail - 0x40); 0 = undefined."""
import sys
out = sys.argv[1] if len(sys.argv) > 1 else "src/recursos/big5_tabla.inc"
rows = []
for b1 in range(0x81, 0xFF):
    row = []
    for b2 in range(0x40, 0xFF):
        try:
            s = bytes([b1, b2]).decode("cp950")
            cp = ord(s) if len(s) == 1 and ord(s) < 0x10000 else 0
        except UnicodeDecodeError:
            cp = 0
        row.append(cp)
    rows.append(row)
with open(out, "w") as f:
    f.write("// Generated by herramientas/generar_big5.py (CP950 -> UTF-16). Do not edit.\n")
    for row in rows:
        f.write(",".join(f"0x{c:04X}" if c else "0" for c in row) + ",\n")
