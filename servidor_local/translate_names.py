#!/usr/bin/env python3 -I
"""Generate name_fixes.tsv and the name section of corregir_db.sql.

Korean name columns of the L1J-JP database are replaced by (1) the l1j-en/classic name of the same
id when the sprite ids also match, else (2) a hand translation from name_translations.tsv
(" => "-separated; whole string first, then Korean fragments, longest first; `$N` desc ids are kept).

Usage: translate_names.py <mariadb-bin> <socket> <l1j-en-classic l1jdb_m10.sql> <desc-e.tbl dump>

An l1j-en `$N` id is kept only when desc-e entry N agrees with the l1j-en plain `name` (the two
projects number descs differently); otherwise the plain l1j-en `name` text is used. Rows whose Korean
text mixes in `$N` ids are always hand translated (l1j-en reuses ids and abbreviates places).
Re-runnable on a fixed DB: only still-Korean rows are regenerated, other TSV rows are kept.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KOREAN = re.compile("[가-힣]")
JAPANESE = re.compile("[\u3040-\u30ff\u4e00-\u9fff]")
BEGIN = "-- BEGIN name_fixes (generated by translate_names.py)"
END = "-- END name_fixes"
TMP_DB = "l1en_tmp"

# table -> (key col, [(local col...)], en table, en key, [(local gfx, en gfx)], name cols)
TABLES = {
    "etc_items": ("etcitem", "item_id", [("inv_gfx_id", "invgfx"), ("grd_gfx_id", "grdgfx")],
                  [("unidentified_name_id", "unidentified_name_id"), ("identified_name_id", "identified_name_id")]),
    "weapons": ("weapon", "item_id", [("inv_gfx_id", "invgfx"), ("grd_gfx_id", "grdgfx")],
                [("unidentified_name_id", "unidentified_name_id"), ("identified_name_id", "identified_name_id")]),
    "armors": ("armor", "item_id", [("inv_gfx_id", "invgfx"), ("grd_gfx_id", "grdgfx")],
               [("unidentified_name_id", "unidentified_name_id"), ("identified_name_id", "identified_name_id")]),
    "npcs": ("npc", "npcid", [("gfx_id", "gfxid")], [("name_id", "nameid")]),
}


def run(mariadb, sock, db, sql, stdin=None):
    args = [mariadb, "--socket=" + sock, "-uroot", "--default-character-set=utf8mb4", "-N", "-B"]
    if db:
        args.append(db)
    if sql:
        args += ["-e", sql]
    out = subprocess.run(args, check=True, capture_output=True, text=True, stdin=stdin).stdout
    return [line.split("\t") for line in out.splitlines()]


def load_translations():
    whole = {}
    with open(os.path.join(HERE, "name_translations.tsv"), encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line and not line.startswith("#"):
                ko, en = line.split(" => ")
                whole[ko] = en
    return whole


def translate(text, whole):
    if text in whole:
        return whole[text]
    out = text
    for ko in sorted(whole, key=len, reverse=True):
        # Match whole words only so short entries ("알") cannot corrupt longer Korean words.
        out = re.sub(r"(?<![가-힣])" + re.escape(ko) + r"(?![가-힣])", lambda _m, en=whole[ko]: en, out)
    out = re.sub(r"\$ (\d+)", r"$\1", out)
    out = re.sub(r"\s+", " ", out).strip()
    return None if KOREAN.search(out) or JAPANESE.search(out) else out


def load_desc(path):
    """desc-e.tbl dump: index n is file line n + 2 (1-based)."""
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()
    return lambda n: lines[n + 1].strip() if 0 <= n + 1 < len(lines) else ""


def pick_english(en_id, en_name, desc):
    """Return the l1j-en name to use, or None if it is unusable."""
    m = re.fullmatch(r"\$(\d+)", en_id or "")
    plain = en_name if en_name not in ("", "NULL") and not KOREAN.search(en_name) else None
    if plain and plain.startswith("Unknown"):
        plain = None  # l1j-en placeholder names ("Unknown 41209")
    if en_id and en_id.startswith("Unknown"):
        return plain
    if m:
        text = desc(int(m.group(1)))
        if plain and text and text.lower() in plain.lower() + " " and text.lower() != "dummy" or \
                plain and text and plain.lower() in text.lower():
            return en_id
        return plain
    if en_id in ("", "NULL") or KOREAN.search(en_id):
        return plain
    return en_id


def sql_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


def main():
    mariadb, sock, ref_sql, desc_path = sys.argv[1:5]
    desc = load_desc(desc_path)
    whole = load_translations()
    run(mariadb, sock, None, f"DROP DATABASE IF EXISTS {TMP_DB}; CREATE DATABASE {TMP_DB} CHARACTER SET utf8mb4")
    with open(ref_sql, "rb") as f:
        subprocess.run([mariadb, "--socket=" + sock, "-uroot", TMP_DB], check=True, stdin=f)
    rows, unresolved, stats = [], {}, {}
    try:
        for table, (en_table, en_key, gfx, cols) in TABLES.items():
            where = " OR ".join(f"l.{c} REGEXP '[가-힣]'" for c, _ in cols)
            sel = ", ".join(f"l.{c}, e.{ec}" for c, ec in cols) + ", e.name"
            gfx_ok = " AND ".join(f"e.{eg} = l.{lg}" for lg, eg in gfx)
            sql = (f"SELECT l.id, ({gfx_ok}) AS ok, {sel} FROM l1jdb_363.{table} l "
                   f"LEFT JOIN {TMP_DB}.{en_table} e ON e.{en_key} = l.id WHERE {where} ORDER BY l.id")
            for rec in run(mariadb, sock, None, sql):
                rid, ok, vals, en_name = rec[0], rec[1], rec[2:-1], rec[-1]
                for i, (col, _) in enumerate(cols):
                    old, en = vals[2 * i], vals[2 * i + 1]
                    if not KOREAN.search(old):
                        continue
                    en_use = None
                    if ok == "1" and not re.search(r"\$\d+", old):
                        en_use = pick_english(en, en_name, desc)
                    if en_use:
                        new, src = en_use, "l1j-en"
                    else:
                        new, src = translate(old, whole), "translated"
                    if new is None:
                        unresolved[old] = unresolved.get(old, 0) + 1
                        continue
                    rows.append((table, rid, col, old, new, src))
                    stats[(table, src)] = stats.get((table, src), 0) + 1
    finally:
        run(mariadb, sock, None, f"DROP DATABASE IF EXISTS {TMP_DB}")
    if unresolved:
        for k in sorted(unresolved):
            print("UNRESOLVED", k, file=sys.stderr)
        sys.exit(f"{len(unresolved)} unresolved strings")
    # Keep rows of earlier runs whose DB rows are already fixed (no longer Korean); fresh rows win.
    tsv = os.path.join(HERE, "name_fixes.tsv")
    merged = {}
    if os.path.exists(tsv):
        with open(tsv, encoding="utf-8") as f:
            for line in list(f)[1:]:
                r = tuple(line.rstrip("\n").split("\t"))
                merged[r[:3]] = r
    for r in rows:
        merged[r[:3]] = r
    rows = sorted(merged.values(), key=lambda r: (r[0], int(r[1]), r[2]))
    with open(tsv, "w", encoding="utf-8") as f:
        f.write("table\tid\tcolumn\told\tnew\tsource\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
    lines = [BEGIN, "SET NAMES utf8mb4;"]
    for table, rid, col, old, new, _ in rows:
        lines.append(f"UPDATE `{table}` SET `{col}` = {sql_str(new)} WHERE id = {rid} AND `{col}` = {sql_str(old)};")
    lines.append(END)
    path = os.path.join(HERE, "corregir_db.sql")
    text = open(path, encoding="utf-8").read()
    text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", text, flags=re.S).rstrip("\n")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text + "\n\n" + "\n".join(lines) + "\n")
    for k in sorted(stats):
        print(k, stats[k])


if __name__ == "__main__":
    main()
