#!/usr/bin/env python3
"""Generates src/recursos/fuente_html_datos.inc: hinted 1-bit glyph bitmaps of Liberation Sans Regular (SIL OFL 1.1,
licencias/LiberationSans-OFL.txt) at 11 ppem. They stand in for the GDI "Arial" face with which the 2009 client draws
the NPC HTML pages (see recursos/fuente_ttf.cpp): lfHeight 13 resolves to 11 ppem (ascent 10 + descent 3 = 13, which is
exactly what FreeType reports for this font), quality 0, and Windows XP draws Arial at that size hinted and without
anti-aliasing. FreeType's monochrome hinting (through Pillow) reproduces that look.

Needs Pillow (only to generate).  Usage: python3 tools/generar_fuente_html.py
"""
import os

from PIL import Image, ImageDraw, ImageFont

RAIZ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORIGEN = os.path.join(RAIZ, "datos", "fuentes", "LiberationSans-Regular.ttf")
SALIDA = os.path.join(RAIZ, "src", "recursos", "fuente_html_datos.inc")
RANGOS = [(0x20, 0x7E), (0xA0, 0xFF), (0x2013, 0x2014), (0x2018, 0x201E), (0x2026, 0x2026), (0x20AC, 0x20AC)]
PPEM, ASCENSO, ALTO = 11, 10, 13
PLUMA = 2  # column of the pen in the 16-bit rows: lets glyphs hang up to 2 px left of the origin


def main():
    fuente = ImageFont.truetype(ORIGEN, PPEM, layout_engine=ImageFont.Layout.BASIC)
    assert fuente.getmetrics() == (ASCENSO, ALTO - ASCENSO), fuente.getmetrics()
    cps, anchos, filas = [], [], []
    for lo, hi in RANGOS:
        for cp in range(lo, hi + 1):
            if not fuente.getmask(chr(cp), mode="1").getbbox() and cp not in (0x20, 0xA0):
                continue  # not in the font
            im = Image.new("L", (16, ALTO), 0)
            d = ImageDraw.Draw(im)
            d.fontmode = "1"
            d.text((PLUMA, ASCENSO), chr(cp), font=fuente, fill=255, anchor="ls")
            rows = []
            for y in range(ALTO):
                v = 0
                for x in range(16):
                    if im.getpixel((x, y)):
                        v |= 0x8000 >> x
                rows.append(v)
            cps.append(cp)
            anchos.append(int(fuente.getlength(chr(cp), mode="1")))
            filas.append(rows)
    out = [
        "// Generated by tools/generar_fuente_html.py from datos/fuentes/LiberationSans-Regular.ttf (SIL OFL 1.1).",
        "// Hinted 1-bit glyphs at 11 ppem. Do not edit by hand.",
        f"constexpr int FUENTE_HTML_PLUMA = {PLUMA};  // pen column inside the 16-bit rows (bit 15 = column 0)",
        f"constexpr int FUENTE_HTML_ASCENSO = {ASCENSO};",
        f"constexpr int FUENTE_HTML_N = {len(cps)};",
        "constexpr unsigned short FUENTE_HTML_CP[FUENTE_HTML_N] = {" + ", ".join(f"0x{c:x}" for c in cps) + "};",
        "constexpr unsigned char FUENTE_HTML_ANCHO[FUENTE_HTML_N] = {" + ", ".join(str(a) for a in anchos) + "};",
        f"constexpr unsigned short FUENTE_HTML_FILAS[FUENTE_HTML_N][{ALTO}] = {{",
    ]
    for r in filas:
        out.append("    {" + ", ".join(f"0x{v:04x}" for v in r) + "},")
    out.append("};")
    with open(SALIDA, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"{SALIDA}: {len(cps)} glyphs")


if __name__ == "__main__":
    main()
