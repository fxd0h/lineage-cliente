#!/usr/bin/env python3
"""Generates src/recursos/fuente_html_hd_datos.inc: Liberation Sans Regular (SIL OFL 1.1, licencias/LiberationSans-OFL.txt)
subset to the same code points as the pixel face (tools/generar_fuente_html.py), unhinted. The HD text pass
(texto_hd=1) rasterizes its real outlines at the display scale; layout still uses the hinted integer advances of the
pixel face, so lines wrap exactly as before.

Needs fonttools (only to generate).  Usage: python3 tools/generar_fuente_html_hd.py
"""
import os
import subprocess
import sys
import tempfile

RAIZ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORIGEN = os.path.join(RAIZ, "datos", "fuentes", "LiberationSans-Regular.ttf")
SALIDA = os.path.join(RAIZ, "src", "recursos", "fuente_html_hd_datos.inc")
RANGOS = "U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201E,U+2026,U+20AC"


def main():
    with tempfile.TemporaryDirectory() as tmp:
        recortada = os.path.join(tmp, "recortada.ttf")
        subprocess.run([sys.executable, "-m", "fontTools.subset", ORIGEN, "--unicodes=" + RANGOS,
                        "--layout-features=", "--no-hinting", "--desubroutinize", "--output-file=" + recortada],
                       check=True)
        with open(recortada, "rb") as f:
            datos = f.read()
    lineas = [
        "// Generated by tools/generar_fuente_html_hd.py from datos/fuentes/LiberationSans-Regular.ttf (SIL OFL 1.1).",
        "// Do not edit by hand.",
        f"constexpr unsigned int FUENTE_HTML_HD_TAM = {len(datos)};",
        "constexpr unsigned char FUENTE_HTML_HD_DATOS[] = {",
    ]
    for i in range(0, len(datos), 16):
        lineas.append("    " + ", ".join(f"0x{b:02x}" for b in datos[i:i + 16]) + ",")
    lineas.append("};")
    with open(SALIDA, "w", encoding="utf-8") as f:
        f.write("\n".join(lineas) + "\n")
    print(f"{SALIDA}: {len(datos)} bytes")


if __name__ == "__main__":
    main()
